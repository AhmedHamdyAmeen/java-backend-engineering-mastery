"""Validate catalog/modules.yaml and regenerate catalog/INDEX.md and levels/*/README.md.

Usage: py tools/build.py            (validate + generate)
       py tools/build.py --check    (validate only; exit 1 if generated files are stale)
"""

import os
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "catalog" / "modules.yaml"
STATUSES = ["outline", "detailed", "scripted", "recorded", "published", "retired"]
INTERVIEW_GUIDE = "interview-prep.md"
GENERATED_NOTE ="<!-- GENERATED by tools/build.py from catalog/modules.yaml. Do not edit by hand. -->"


def validate(data):
    errors = []
    levels = data["levels"]
    modules = data["modules"]
    phases = {p["id"]: (lvl, p) for lvl in levels for p in lvl["phases"]}
    level_codes = {lvl["code"] for lvl in levels}

    for mid, count in Counter(m["id"] for m in modules).items():
        if count > 1:
            errors.append(f"duplicate module id {mid}")
    for n, count in Counter(m["n"] for m in modules if m.get("n") is not None).items():
        if count > 1:
            errors.append(f"duplicate roadmap number n={n}")

    position = {m["id"]: i for i, m in enumerate(modules)}
    for i, m in enumerate(modules):
        mid = m["id"]
        if not re.fullmatch(r"[A-Z]{3}-\d{3}", mid):
            errors.append(f"{mid}: id does not match <LEVEL>-<nnn>")
        if mid[:3] not in level_codes:
            errors.append(f"{mid}: unknown level code")
        if m["phase"] not in phases:
            errors.append(f"{mid}: unknown phase {m['phase']}")
        elif not m["phase"].startswith(mid[:3] + "-"):
            errors.append(f"{mid}: phase {m['phase']} belongs to another level")
        if m.get("status") not in STATUSES:
            errors.append(f"{mid}: status must be one of {STATUSES}")
        if m.get("status") != "outline" and "prereqs" not in m:
            errors.append(f"{mid}: non-outline modules must declare prereqs")
        for pre in m.get("prereqs", []):
            if pre not in position:
                errors.append(f"{mid}: prerequisite {pre} does not exist")
            elif position[pre] >= i:
                errors.append(f"{mid}: prerequisite {pre} is not taught earlier")
        for co in m.get("co_requisites", []):
            if co not in position:
                errors.append(f"{mid}: co-requisite {co} does not exist")

    # Detailed modules must have a spec section in their phase file.
    for m in modules:
        if m.get("status") in ("outline", "retired") or m["phase"] not in phases:
            continue
        lvl, phase = phases[m["phase"]]
        if "file" not in phase:
            errors.append(f"{m['id']}: phase {phase['id']} has no spec file")
            continue
        spec = ROOT / "levels" / lvl["dir"] / phase["file"]
        if not spec.exists():
            errors.append(f"{m['id']}: spec file {spec.relative_to(ROOT)} is missing")
        elif not (section := re.search(rf"^### {m['id']} · .*?(?=^### |\Z)", spec.read_text(encoding="utf-8"), re.MULTILINE | re.DOTALL)):
            errors.append(f"{m['id']}: no '### {m['id']} · ' heading in {spec.relative_to(ROOT)}")
        else:
            # The module's video estimate must equal the sum of its lecture durations.
            text = section.group(0)
            video = re.search(r"\*\*Video:\*\* (\d+) min", text)
            lectures = sum(int(x) for x in re.findall(rf"^\| {m['id']}-L\d\d \| .* \| (\d+) \|$", text, re.MULTILINE))
            if not video:
                errors.append(f"{m['id']}: no '**Video:** <n> min' estimate")
            elif int(video.group(1)) != lectures:
                errors.append(f"{m['id']}: video estimate {video.group(1)} min != lecture total {lectures} min")
    return errors + validate_interview_guides(data, phases, position)


def validate_interview_guides(data, phases, position):
    """Every interview question must point at real modules (learned) and real labs or capstones (practiced)."""
    errors = []
    capstones = {lvl["capstone"]["id"] for lvl in data["levels"]}
    module_phase = {m["id"]: m["phase"] for m in data["modules"]}
    for lvl in data["levels"]:
        guide = ROOT / "levels" / lvl["dir"] / INTERVIEW_GUIDE
        if not guide.exists():
            continue
        name = guide.relative_to(ROOT)
        text = guide.read_text(encoding="utf-8")
        # Any ID mentioned anywhere in the guide must exist.
        for ref in sorted(set(re.findall(r"\b[A-Z]{3}-(?:\d{3}(?:-LAB\d)?|CAP)\b", text))):
            if ref.endswith("-CAP"):
                if ref not in capstones:
                    errors.append(f"{name}: unknown capstone {ref}")
                continue
            mid = ref[:7]
            if mid not in position:
                errors.append(f"{name}: unknown module {mid}")
            elif "-LAB" in ref:
                plvl, phase = phases[module_phase[mid]]
                spec = ROOT / "levels" / plvl["dir"] / phase.get("file", "")
                if not phase.get("file") or not spec.exists() or f"`{ref}`" not in spec.read_text(encoding="utf-8"):
                    errors.append(f"{name}: lab {ref} is not defined in its module spec")
        blocks = re.split(r"(?m)^(?=### Q\d+ · )", text)[1:]
        if not blocks:
            errors.append(f"{name}: no '### Q<n> · ' questions found")
        for block in blocks:
            qid = block.split(" · ", 1)[0][4:]
            learned = re.search(r"^\*\*Learned in:\*\*(.*)$", block, re.MULTILINE)
            practiced = re.search(r"^\*\*Practiced in:\*\*(.*)$", block, re.MULTILINE)
            if not learned or not re.search(r"[A-Z]{3}-\d{3}\b", learned.group(1)):
                errors.append(f"{name} {qid}: needs a '**Learned in:**' line with at least one module ID")
            if not practiced or not re.search(r"[A-Z]{3}-(?:\d{3}-LAB\d|CAP)\b", practiced.group(1)):
                errors.append(f"{name} {qid}: needs a '**Practiced in:**' line with at least one lab or capstone ID")
    return errors


def module_link(m, lvl, phase, from_dir):
    """Markdown link to a module's spec section, or its bare ID when not yet detailed."""
    if m.get("status") in ("outline", "retired") or "file" not in phase:
        return f"`{m['id']}`"
    anchor = re.sub(r"[^a-z0-9 -]", "", f"{m['id']} · {m['title']}".lower()).replace(" ", "-")
    target = Path(os.path.relpath(ROOT / "levels" / lvl["dir"] / phase["file"], from_dir))
    return f"[`{m['id']}`]({target.as_posix()}#{anchor})"


def build_index(data):
    by_phase = {}
    for m in data["modules"]:
        by_phase.setdefault(m["phase"], []).append(m)
    counts = Counter(m["status"] for m in data["modules"])
    out = [GENERATED_NOTE, "", "# Module Index", ""]
    out.append(f"{len(data['modules'])} modules · " + " · ".join(f"{counts[s]} {s}" for s in STATUSES if counts[s]))
    out.append("")
    for lvl in data["levels"]:
        out += [f"## {lvl['order']}. {lvl['name']} (`{lvl['code']}`)", ""]
        for phase in lvl["phases"]:
            out += [f"### {phase['id']} — {phase['title']}", "", "| ID | n | Module | Status | Prerequisites |", "| --- | --- | --- | --- | --- |"]
            for m in by_phase.get(phase["id"], []):
                pre = ", ".join(m.get("prereqs", [])) or ("—" if "prereqs" in m else "")
                if m.get("co_requisites"):
                    pre += f" (co: {', '.join(m['co_requisites'])})"
                n = m["n"] if m.get("n") is not None else "new"
                out.append(f"| {module_link(m, lvl, phase, ROOT / 'catalog')} | {n} | {m['title']} | {m['status']} | {pre} |")
            out.append("")
    return "\n".join(out)


def build_level_readme(data, lvl):
    level_dir = ROOT / "levels" / lvl["dir"]
    cap = lvl["capstone"]
    out = [GENERATED_NOTE, "", f"# Level {lvl['order']} — {lvl['name']}", ""]
    out += [f"**Audience:** {lvl['audience']}", "", f"**Graduation outcome:** {lvl['outcome']}", ""]
    out += ["| Structured study | Recorded video | Lessons |", "| --- | --- | --- |", f"| {lvl['study_hours']} h | {lvl['video_hours']} h | {lvl['lessons']} |", ""]
    for phase in lvl["phases"]:
        mods = [m for m in data["modules"] if m["phase"] == phase["id"]]
        title = f"[{phase['title']}]({phase['file']})" if phase.get("file") and (level_dir / phase["file"]).exists() else phase["title"]
        out += [f"## {phase['id']} — {title}", "", "| ID | Module | Topics |", "| --- | --- | --- |"]
        for m in mods:
            out.append(f"| {module_link(m, lvl, phase, level_dir)} | {m['title']} | {m['topics']} |")
        out.append("")
    out += [f"## Capstone — {cap['title']} (`{cap['id']}`)", "", cap["summary"], "", f"**Graduation gate:** {lvl['gate']}", ""]
    out += ["See [`projects/ladder.md`](../../projects/ladder.md) for the full brief and [`assessment/framework.md`](../../assessment/framework.md) for grading.", ""]
    if (level_dir / INTERVIEW_GUIDE).exists():
        out += ["## Interview preparation", "", f"The questions most often asked at this level, how to answer them, and where each was learned and practiced: [`{INTERVIEW_GUIDE}`]({INTERVIEW_GUIDE}).", ""]
    return "\n".join(out)


def main():
    check_only = "--check" in sys.argv
    data = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))
    errors = validate(data)
    if errors:
        print(f"{len(errors)} validation error(s):")
        for e in errors:
            print(f"  - {e}")
        sys.exit(1)

    outputs = {ROOT / "catalog" / "INDEX.md": build_index(data)}
    for lvl in data["levels"]:
        outputs[ROOT / "levels" / lvl["dir"] / "README.md"] = build_level_readme(data, lvl)

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if check_only:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        sys.exit(1 if stale else 0)
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p],encoding="utf-8", newline="\n")
    print(f"OK: {len(data['modules'])} modules valid; {len(stale)} file(s) regenerated.")


if __name__ == "__main__":
    main()
